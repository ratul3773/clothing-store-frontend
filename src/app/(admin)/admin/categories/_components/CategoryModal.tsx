"use client";

import useCategoryModalForm, { type Props } from "../_hooks/useCategoryModalForm";

import { ImagePlus, Trash2 } from "lucide-react";

import Modal from "@/components/cms/Modal";
import { Btn } from "@/components/cms/ui";
import { IMAGE_ACCEPT, validateImageFile } from "@/lib/image";
import { apiErrorMessage } from "@/redux/api.utils";

import { FormField } from "@/components/common/form-field";
import Image from "next/image";

export default function CategoryModal(props: Props) {
  if (!props.open) return null;
  return <CategoryModalContent key={props.editing?.id ?? "new"} {...props} />;
}

function CategoryModalContent({ onOpenChange, categories, editing }: Props) {
  const {
    toast,
    toastError,
    inputRef,
    uploadState,
    removeImage,
    removeState,
    selectedImage,
    setSelectedImage,
    imagePreview,
    setImageRemoved,
    forbiddenParentIds,
    rows,
    form,
    saving,
    parentId,
    existingImageUrl,
    imageRequired,
    hasImage,
    onSubmit,
  } = useCategoryModalForm({ onOpenChange, categories, editing });

  return (
    <Modal
      open
      onOpenChange={onOpenChange}
      title={editing ? "Edit category" : "New category"}
      description="Categories can be nested. Slugs are generated by the server."
      size="lg"
      footer={
        <>
          <Btn onClick={() => onOpenChange(false)} disabled={saving}>
            Cancel
          </Btn>
          <Btn
            type="submit"
            form="category-form"
            variant="primary"
            disabled={saving || (imageRequired && !hasImage)}
          >
            {saving ? "Saving…" : editing ? "Save category" : "Create category"}
          </Btn>
        </>
      }
    >
      <form id="category-form" onSubmit={onSubmit} className="space-y-4">
        <div className="grid gap-4 sm:grid-cols-2">
          <FormField isAdmin isInput id="name" form={form}
            name="name"
            label="Name"
            placeholder="e.g. Shirts" />
          <FormField isAdmin isSelect id="parentId" form={form}
            name="parentId"
            label="Parent category"
            placeholder="No parent (top level)"
            options={rows.map((category) => ({
              value: category.id,
              label: `${"— ".repeat(category.depth)}${category.name}`,
              disabled: forbiddenParentIds.has(category.id),
            }))}
            description="A category cannot be its own parent or a descendant." />
          <FormField isAdmin isInput id="sortOrder" form={form}
            name="sortOrder"
            label="Sort order"
            inputMode="numeric"
            placeholder="0"
            description="Lower numbers appear first." />
          <FormField isAdmin isSwitch id="isActive" form={form}
            name="isActive"
            label="Active"
            description="Inactive categories cannot be used for publishing products." />
        </div>

        <FormField isAdmin isTextArea id="description" form={form}
          name="description"
          label="Description"
          rows={3}
          placeholder="Optional category description" />

        <div className="grid gap-4 sm:grid-cols-2">
          <FormField isAdmin isInput id="seoTitle" form={form}
            name="seoTitle"
            label="SEO title"
            placeholder="Optional search title" />
          <FormField isAdmin isInput id="seoDescription" form={form}
            name="seoDescription"
            label="SEO description"
            placeholder="Optional search description" />
        </div>

        {!parentId && (
          <div className="rounded border border-border p-3">
            <p className="mb-2 text-xs font-medium text-foreground/80">
              Category image{" "}
              {imageRequired && <span className="text-destructive">*</span>}
            </p>

            <div className="flex items-center gap-3">
              <div className="size-20 shrink-0 overflow-hidden rounded border border-border bg-muted">
                {imagePreview || existingImageUrl ? (
                  <Image
                    src={imagePreview ?? existingImageUrl ?? ""}
                    width={80}
                    height={80}
                    alt="Category preview"
                    className="size-full object-cover"
                  />
                ) : null}
              </div>

              <div className="flex flex-wrap gap-2">
                <Btn
                  size="sm"
                  onClick={() => inputRef.current?.click()}
                  disabled={uploadState.isLoading || saving}
                >
                  <ImagePlus className="size-3.5" />
                  {selectedImage || existingImageUrl
                    ? "Change image"
                    : "Choose image"}
                </Btn>

                {selectedImage && (
                  <Btn
                    size="sm"
                    variant="dangerOutline"
                    onClick={() => setSelectedImage(null)}
                    disabled={saving || uploadState.isLoading}
                  >
                    <Trash2 className="size-3.5" />
                  </Btn>
                )}

                {editing && existingImageUrl && !selectedImage && (
                  <Btn
                    size="sm"
                    variant="dangerOutline"
                    disabled={uploadState.isLoading || removeState.isLoading}
                    onClick={async () => {
                      try {
                        await removeImage(editing.id).unwrap();
                        setImageRemoved(true);
                        toast("Category image removed.");
                      } catch (error) {
                        toast(
                          apiErrorMessage(
                            error,
                            "The category image could not be removed.",
                          ),
                        );
                      }
                    }}
                  >
                    <Trash2 className="size-3.5" />
                  </Btn>
                )}

                {imageRequired ? (
                  <p className="mt-2 text-xs text-muted-foreground">
                    An image is required for top-level categories. JPEG, PNG,
                    WebP, or AVIF · max 5 MB.
                  </p>
                ) : (
                  <p className="mt-2 text-xs text-muted-foreground">
                    Optional for subcategories. JPEG, PNG, WebP, or AVIF · max 5
                    MB.
                  </p>
                )}
              </div>
            </div>

            <input
              ref={inputRef}
              type="file"
              accept={IMAGE_ACCEPT}
              className="hidden"
              onChange={(event) => {
                const file = event.target.files?.[0];

                if (file) {
                  const problem = validateImageFile(file);

                  if (problem) {
                    toastError(problem);
                  } else {
                    setSelectedImage(file);
                  }
                }
                event.target.value = "";
              }}
            />
          </div>
        )}
      </form>
    </Modal>
  );
}
