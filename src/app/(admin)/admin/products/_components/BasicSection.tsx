"use client";

import type { UseFormReturn } from "react-hook-form";

import { Card, CardHeader } from "@/components/cms/ui";
import { useGetAdminCategoriesQuery } from "@/redux/apis/category.api";
import { toCategoryRows } from "@/redux/apis/types/category.types";

import type { ProductCoreFormValues } from "../_schemas/product.schema";
import { slugPreview } from "../_utils/products.utils";
import { SelectField, SwitchField, TextField } from "../../_components/form-controls";
import BadgesField from "./BadgesField";

export default function BasicSection({
  form,
}: {
  form: UseFormReturn<ProductCoreFormValues>;
}) {
  const { data: categories, isLoading } = useGetAdminCategoriesQuery();
  const rows = categories ? toCategoryRows(categories) : [];
  const name = form.watch("name");
  const parentCategoryId = form.watch("parentCategoryId");

  const parentOptions = rows
    .filter((category) => category.depth === 0)
    .map((category) => ({
      value: category.id,
      label: category.name,
      disabled: !category.isActive,
    }));
  const subcategoryOptions = rows
    .filter((category) => category.parentId === parentCategoryId)
    .map((category) => ({
      value: category.id,
      label: category.name,
      disabled: !category.isActive,
    }));

  const categoryHint = parentCategoryId
    ? "Choose the subcategory where this product belongs."
    : "Choose a category first.";

  const parentChange = (value: string) => {
    form.setValue("parentCategoryId", value, { shouldValidate: true });
    form.setValue("categoryId", "", { shouldValidate: true });
  };

  const subcategoryOptionsWithPlaceholder = subcategoryOptions.length
    ? subcategoryOptions
    : [{ value: "__empty__", label: "No subcategories available", disabled: true }];

  return (
    <Card>
      <CardHeader
        title="Basic information"
        description="The product slug is generated by the server from the name."
      />
      <div className="grid gap-4 p-4 sm:grid-cols-2">
        <TextField
          form={form}
          name="name"
          label="Product name"
          placeholder="e.g. Dhaka Oxford Shirt"
          className="sm:col-span-2"
        />
        <TextField
          form={form}
          name="code"
          label="Product code"
          placeholder="e.g. OXF-SHIRT"
          hint="Letters, numbers, underscores, and hyphens. Variant SKUs derive from it."
        />
        <SelectField
          form={form}
          name="parentCategoryId"
          label="Category"
          placeholder={isLoading ? "Loading categories…" : "Select a category"}
          disabled={isLoading}
          options={parentOptions}
          onValueChange={parentChange}
          hint={categoryHint}
        />
        <SelectField
          form={form}
          name="categoryId"
          label="Subcategory"
          placeholder={!parentCategoryId ? "Select a category first" : "Select a subcategory"}
          disabled={isLoading || !parentCategoryId || subcategoryOptions.length === 0}
          options={subcategoryOptionsWithPlaceholder}
          hint={
            name.trim()
              ? `Slug preview: ${slugPreview(name) || "—"}`
              : "Products must be assigned to an active subcategory."
          }
        />
        <BadgesField
          form={form}
          name="badges"
          label="Badges"
          hint="Optional. Up to five badges."
        />
        <SwitchField
          form={form}
          name="isExchangeEligible"
          label="Exchange eligible"
          description="Allow customers to request an exchange for this product."
        />
      </div>
    </Card>
  );
}
