"use client";

import useBasicSection from "../_hooks/useBasicSection";

import type { UseFormReturn } from "react-hook-form";

import { Card, CardHeader } from "@/components/cms/ui";

import { FormField } from "@/components/common/form-field";
import type { ProductCoreFormValues } from "../_schemas/product.schema";
import { slugPreview } from "../_utils/products.utils";
import BadgesField from "./BadgesField";

export default function BasicSection({
  form,
}: {
  form: UseFormReturn<ProductCoreFormValues>;
}) {
  const {
    isLoading,
    name,
    parentCategoryId,
    parentOptions,
    subcategoryOptions,
    categoryHint,
    parentChange,
    subcategoryOptionsWithPlaceholder,
  } = useBasicSection({
    form,
  });

  return (
    <Card>
      <CardHeader
        title="Basic information"
        description="The product slug is generated by the server from the name."
      />
      <div className="grid gap-4 p-4 sm:grid-cols-2">
        <FormField isAdmin isInput id="name" form={form}
          name="name"
          label="Product name"
          placeholder="e.g. Dhaka Oxford Shirt"
          className="sm:col-span-2" />
        <FormField isAdmin isInput id="code" form={form}
          name="code"
          label="Product code"
          placeholder="e.g. OXF-SHIRT"
          description="Letters, numbers, underscores, and hyphens. Variant SKUs derive from it." />
        <FormField isAdmin isSelect id="parentCategoryId" form={form}
          name="parentCategoryId"
          label="Category"
          placeholder={isLoading ? "Loading categories…" : "Select a category"}
          disabled={isLoading}
          options={parentOptions}
          onValueChange={parentChange}
          description={categoryHint} />
        <FormField isAdmin isSelect id="categoryId" form={form}
          name="categoryId"
          label="Subcategory"
          placeholder={
            !parentCategoryId
              ? "Select a category first"
              : "Select a subcategory"
          }
          disabled={
            isLoading || !parentCategoryId || subcategoryOptions.length === 0
          }
          options={subcategoryOptionsWithPlaceholder}
          description={
            name.trim()
              ? `Slug preview: ${slugPreview(name) || "—"}`
              : "Products must be assigned to an active subcategory."
          } />
        <BadgesField
          form={form}
          name="badges"
          label="Badges"
          hint="Optional. Up to five badges."
        />
        <FormField isAdmin isSwitch id="isExchangeEligible" form={form}
          name="isExchangeEligible"
          label="Exchange eligible"
          description="Allow customers to request an exchange for this product." />
      </div>
    </Card>
  );
}
